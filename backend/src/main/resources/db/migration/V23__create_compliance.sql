CREATE TABLE marketplace.compliance_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_type VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    subject_type VARCHAR(32) NOT NULL,
    subject_id VARCHAR(64) NOT NULL,
    opened_by VARCHAR(64),
    description VARCHAR(2000),
    resolution VARCHAR(2000),
    opened_at TIMESTAMP NOT NULL,
    closed_at TIMESTAMP
);

CREATE TABLE marketplace.disputes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES marketplace.orders (id),
    opened_by VARCHAR(64) NOT NULL,
    respondent_id VARCHAR(64),
    status VARCHAR(32) NOT NULL,
    reason VARCHAR(2000) NOT NULL,
    resolution VARCHAR(2000),
    opened_at TIMESTAMP NOT NULL,
    resolved_at TIMESTAMP
);

CREATE INDEX idx_compliance_cases_subject ON marketplace.compliance_cases (subject_type, subject_id);
CREATE INDEX idx_disputes_order ON marketplace.disputes (order_id);
