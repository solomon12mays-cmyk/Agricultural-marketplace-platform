CREATE TABLE marketplace.listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_type VARCHAR(32) NOT NULL,
    seller_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL REFERENCES marketplace.products (id),
    quantity_available NUMERIC(19, 3) NOT NULL,
    unit VARCHAR(16) NOT NULL,
    price_per_unit NUMERIC(19, 2) NOT NULL,
    currency VARCHAR(8) NOT NULL,
    status VARCHAR(32) NOT NULL,
    region VARCHAR(64),
    starts_at TIMESTAMP,
    ends_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE INDEX idx_listings_seller ON marketplace.listings (seller_type, seller_id);
CREATE INDEX idx_listings_product ON marketplace.listings (product_id);
CREATE INDEX idx_listings_status ON marketplace.listings (status);
