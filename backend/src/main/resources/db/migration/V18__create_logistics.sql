CREATE TABLE marketplace.logistics_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES marketplace.orders (id),
    driver_id BIGINT REFERENCES marketplace.drivers (id),
    vehicle_id BIGINT REFERENCES marketplace.vehicles (id),
    status VARCHAR(32) NOT NULL,
    pickup_address VARCHAR(255),
    dropoff_address VARCHAR(255),
    quoted_price NUMERIC(19, 2),
    currency VARCHAR(8),
    distance_km NUMERIC(10, 2),
    assigned_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE INDEX idx_logistics_assignments_order ON marketplace.logistics_assignments (order_id);
CREATE INDEX idx_logistics_assignments_driver ON marketplace.logistics_assignments (driver_id);
