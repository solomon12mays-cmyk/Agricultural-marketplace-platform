CREATE TABLE marketplace.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES marketplace.users (id),
    channel VARCHAR(16) NOT NULL,
    template VARCHAR(64) NOT NULL,
    subject VARCHAR(255),
    body VARCHAR(2000),
    status VARCHAR(32) NOT NULL,
    sent_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE marketplace.notification_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT NOT NULL REFERENCES marketplace.notifications (id),
    provider VARCHAR(32),
    provider_reference VARCHAR(128),
    status VARCHAR(32) NOT NULL,
    attempt INTEGER NOT NULL,
    error VARCHAR(500),
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_notifications_user ON marketplace.notifications (user_id);
CREATE INDEX idx_notification_deliveries_notification ON marketplace.notification_deliveries (notification_id);
