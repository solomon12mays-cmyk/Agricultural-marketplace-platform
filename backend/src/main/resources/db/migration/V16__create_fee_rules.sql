CREATE TABLE marketplace.fee_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL,
    fee_type VARCHAR(32) NOT NULL,
    percentage NUMERIC(7, 4),
    fixed_amount NUMERIC(19, 2),
    currency VARCHAR(8) NOT NULL,
    applies_to VARCHAR(32),
    active BOOLEAN NOT NULL,
    valid_from TIMESTAMP,
    valid_to TIMESTAMP,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE marketplace.fee_calculations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_type VARCHAR(32) NOT NULL,
    reference_id VARCHAR(64) NOT NULL,
    fee_rule_id BIGINT NOT NULL REFERENCES marketplace.fee_rules (id),
    base_amount NUMERIC(19, 2) NOT NULL,
    fee_amount NUMERIC(19, 2) NOT NULL,
    currency VARCHAR(8) NOT NULL,
    calculated_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_fee_calculations_reference ON marketplace.fee_calculations (reference_type, reference_id);
