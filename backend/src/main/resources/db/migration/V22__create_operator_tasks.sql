CREATE TABLE marketplace.operator_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_type VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    assignee_id BIGINT REFERENCES marketplace.users (id),
    reference_type VARCHAR(32),
    reference_id VARCHAR(64),
    due_at TIMESTAMP,
    completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_operator_tasks_status ON marketplace.operator_tasks (status);
CREATE INDEX idx_operator_tasks_assignee ON marketplace.operator_tasks (assignee_id);
