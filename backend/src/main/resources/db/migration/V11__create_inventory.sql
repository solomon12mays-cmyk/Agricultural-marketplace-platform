CREATE TABLE marketplace.inventory_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_type VARCHAR(32) NOT NULL,
    owner_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL REFERENCES marketplace.products (id),
    quantity NUMERIC(19, 3) NOT NULL,
    reserved_quantity NUMERIC(19, 3) NOT NULL,
    unit VARCHAR(16) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT uq_inventory_owner_product UNIQUE (owner_type, owner_id, product_id)
);

CREATE TABLE marketplace.inventory_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES marketplace.inventory_accounts (id),
    type VARCHAR(32) NOT NULL,
    quantity NUMERIC(19, 3) NOT NULL,
    reference_type VARCHAR(32),
    reference_id VARCHAR(64),
    balance_after NUMERIC(19, 3) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_inventory_transactions_account ON marketplace.inventory_transactions (account_id);
