CREATE TABLE marketplace.roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(128) NOT NULL,
    description VARCHAR(500)
);

CREATE TABLE marketplace.role_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL REFERENCES marketplace.roles (id),
    permission_id BIGINT NOT NULL,
    CONSTRAINT uq_role_permissions UNIQUE (role_id, permission_id)
);

ALTER TABLE marketplace.user_roles
    ADD CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES marketplace.roles (id);
