CREATE TABLE marketplace.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(64) NOT NULL UNIQUE,
    buyer_type VARCHAR(32) NOT NULL,
    buyer_id BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL,
    payment_status VARCHAR(32) NOT NULL,
    total_amount NUMERIC(19, 2) NOT NULL,
    currency VARCHAR(8) NOT NULL,
    delivery_region VARCHAR(64),
    delivery_address VARCHAR(255),
    notes VARCHAR(500),
    placed_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE TABLE marketplace.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES marketplace.orders (id),
    listing_id BIGINT NOT NULL REFERENCES marketplace.listings (id),
    product_id BIGINT NOT NULL REFERENCES marketplace.products (id),
    quantity NUMERIC(19, 3) NOT NULL,
    unit VARCHAR(16) NOT NULL,
    unit_price NUMERIC(19, 2) NOT NULL,
    line_total NUMERIC(19, 2) NOT NULL
);

CREATE TABLE marketplace.order_state_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES marketplace.orders (id),
    from_status VARCHAR(32),
    to_status VARCHAR(32) NOT NULL,
    changed_by VARCHAR(64),
    reason VARCHAR(500),
    changed_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_order_items_order ON marketplace.order_items (order_id);
CREATE INDEX idx_order_state_history_order ON marketplace.order_state_history (order_id);
CREATE INDEX idx_orders_buyer ON marketplace.orders (buyer_type, buyer_id);
