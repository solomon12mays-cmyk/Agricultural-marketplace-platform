    CONSTRAINT ck_grain_lots_expected_price CHECK (expected_price IS NULL OR expected_price >= 0),
    CONSTRAINT ck_grain_lots_min_order CHECK (minimum_order_quantity IS NULL OR minimum_order_quantity > 0)
