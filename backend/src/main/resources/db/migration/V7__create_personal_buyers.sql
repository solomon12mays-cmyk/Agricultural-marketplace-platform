CREATE TABLE marketplace.personal_buyers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES marketplace.users (id),
    full_name VARCHAR(128) NOT NULL,
    phone VARCHAR(32) NOT NULL UNIQUE,
    email VARCHAR(128),
    region VARCHAR(64),
    kyc_status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE INDEX idx_personal_buyers_user_id ON marketplace.personal_buyers (user_id);
