CREATE TABLE marketplace.farms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id BIGINT NOT NULL REFERENCES marketplace.farmers (id),
    name VARCHAR(128) NOT NULL,
    farm_type VARCHAR(64),
    size_hectares NUMERIC(10, 2),
    certification_status VARCHAR(32),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE TABLE marketplace.farm_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id BIGINT NOT NULL REFERENCES marketplace.farms (id),
    region VARCHAR(64),
    zone VARCHAR(64),
    woreda VARCHAR(64),
    village VARCHAR(128),
    latitude NUMERIC(9, 6),
    longitude NUMERIC(9, 6)
);

CREATE INDEX idx_farms_farmer_id ON marketplace.farms (farmer_id);
