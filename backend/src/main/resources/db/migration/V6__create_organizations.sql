CREATE TABLE marketplace.organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES marketplace.users (id),
    name VARCHAR(128) NOT NULL,
    tax_id VARCHAR(64) UNIQUE,
    registration_number VARCHAR(64) UNIQUE,
    phone VARCHAR(32),
    email VARCHAR(128),
    verification_status VARCHAR(32) NOT NULL,
    verification_notes VARCHAR(500),
    verified_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE TABLE marketplace.organization_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES marketplace.organizations (id),
    document_type VARCHAR(64) NOT NULL,
    storage_key VARCHAR(255) NOT NULL,
    status VARCHAR(32) NOT NULL,
    uploaded_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_organization_documents_org ON marketplace.organization_documents (organization_id);
