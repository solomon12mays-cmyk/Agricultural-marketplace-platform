CREATE TABLE marketplace.payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES marketplace.orders (id),
    payer_type VARCHAR(32) NOT NULL,
    payer_id BIGINT NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    currency VARCHAR(8) NOT NULL,
    method VARCHAR(32),
    status VARCHAR(32) NOT NULL,
    gateway VARCHAR(32),
    gateway_reference VARCHAR(128),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    paid_at TIMESTAMP
);

CREATE TABLE marketplace.payment_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES marketplace.payments (id),
    type VARCHAR(32) NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    status VARCHAR(32) NOT NULL,
    gateway_payload VARCHAR(2000),
    processed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE marketplace.payment_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES marketplace.payments (id),
    target_type VARCHAR(32) NOT NULL,
    target_id BIGINT NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_payments_order ON marketplace.payments (order_id);
CREATE INDEX idx_payment_transactions_payment ON marketplace.payment_transactions (payment_id);
CREATE INDEX idx_payment_allocations_payment ON marketplace.payment_allocations (payment_id);
