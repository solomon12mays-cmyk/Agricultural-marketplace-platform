CREATE TABLE marketplace.delivery_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES marketplace.orders (id),
    assignment_id BIGINT REFERENCES marketplace.logistics_assignments (id),
    driver_id BIGINT REFERENCES marketplace.drivers (id),
    status VARCHAR(32) NOT NULL,
    delivered_at TIMESTAMP,
    received_by VARCHAR(64),
    proof_note VARCHAR(500),
    condition_note VARCHAR(500),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE INDEX idx_delivery_records_order ON marketplace.delivery_records (order_id);
