CREATE TABLE marketplace.pickup_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES marketplace.orders (id),
    assignment_id BIGINT REFERENCES marketplace.logistics_assignments (id),
    farmer_id BIGINT REFERENCES marketplace.farmers (id),
    status VARCHAR(32) NOT NULL,
    scheduled_at TIMESTAMP,
    picked_up_at TIMESTAMP,
    location_note VARCHAR(255),
    received_by VARCHAR(64),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE INDEX idx_pickup_records_order ON marketplace.pickup_records (order_id);
