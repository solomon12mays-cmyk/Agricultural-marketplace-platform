CREATE TABLE marketplace.ledger_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(128) NOT NULL,
    account_type VARCHAR(32) NOT NULL,
    owner_type VARCHAR(32),
    owner_id BIGINT,
    currency VARCHAR(8) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE marketplace.journal_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_date DATE NOT NULL,
    reference_type VARCHAR(32) NOT NULL,
    reference_id VARCHAR(64) NOT NULL,
    description VARCHAR(500),
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE marketplace.journal_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id BIGINT NOT NULL REFERENCES marketplace.journal_entries (id),
    account_id BIGINT NOT NULL REFERENCES marketplace.ledger_accounts (id),
    direction VARCHAR(8) NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    currency VARCHAR(8) NOT NULL
);

CREATE INDEX idx_journal_entries_reference ON marketplace.journal_entries (reference_type, reference_id);
CREATE INDEX idx_journal_lines_entry ON marketplace.journal_lines (entry_id);
CREATE INDEX idx_journal_lines_account ON marketplace.journal_lines (account_id);
