CREATE TABLE marketplace.otp_challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_digest VARCHAR(64) NOT NULL,
    purpose VARCHAR(32) NOT NULL,
    code_hash VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    verified_at TIMESTAMP WITH TIME ZONE,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    request_count INTEGER NOT NULL DEFAULT 0,
    request_window_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_sent_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_otp_phone UNIQUE (phone_digest),
    CONSTRAINT ck_otp_purpose CHECK (purpose IN ('REGISTRATION', 'PHONE_VERIFICATION')),
    CONSTRAINT ck_otp_status CHECK (status IN ('ACTIVE', 'VERIFIED', 'EXPIRED', 'LOCKED')),
    CONSTRAINT ck_otp_attempt_count CHECK (attempt_count >= 0),
    CONSTRAINT ck_otp_request_count CHECK (request_count >= 0)
);

CREATE INDEX idx_otp_expiration ON marketplace.otp_challenges (expires_at);
CREATE INDEX idx_otp_status_expiration ON marketplace.otp_challenges (status, expires_at);
