CREATE TABLE marketplace.audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type VARCHAR(128) NOT NULL,
    aggregate_id VARCHAR(64) NOT NULL,
    action VARCHAR(64) NOT NULL,
    actor_id VARCHAR(64),
    details VARCHAR(2000),
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_audit_events_aggregate ON marketplace.audit_events (aggregate_type, aggregate_id);
CREATE INDEX idx_audit_events_created_at ON marketplace.audit_events (created_at);
