CREATE SCHEMA IF NOT EXISTS marketplace;

CREATE TABLE marketplace.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    email VARCHAR(128) UNIQUE,
    phone VARCHAR(32) UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    status VARCHAR(32) NOT NULL,
    password_change_required BOOLEAN NOT NULL,
    failed_login_attempts INTEGER NOT NULL,
    locked_until TIMESTAMP,
    last_login_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE TABLE marketplace.user_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES marketplace.users (id),
    role_id BIGINT NOT NULL,
    CONSTRAINT uq_user_roles UNIQUE (user_id, role_id)
);

CREATE TABLE marketplace.user_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES marketplace.users (id),
    refresh_token_hash VARCHAR(128) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    revoked_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_user_sessions_user_id ON marketplace.user_sessions (user_id);
